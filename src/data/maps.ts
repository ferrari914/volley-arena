import type { EnemySpawn, Obstacle } from '../entities/types';

/**
 * 맵 정의 (DESIGN 10번 · "지형과 장애물이 다른 아레나. 시작 시 선택").
 *
 * **여기는 데이터만 둔다** — 맵을 하나 늘리는 일이 이 파일 한 곳 수정으로 끝나야 한다
 * (DESIGN 모듈 구성의 `data/`). 규칙은 `systems/obstacles.ts`에, 화면은
 * `render/models.ts`에 있고, 둘 다 맵이 몇 개인지 모른다.
 *
 * **맵이 가를 수 있는 것은 둘뿐이다: 기둥과 적이 처음 서는 자리.**
 * 아레나 반지름(`ARENA.radius`)은 맵마다 가르지 않는다 — 카메라 거리·증원 자리
 * (`REINFORCE.spawnRadius` 22m)·부하 장면·그림자 상자가 전부 그 하나에 묶여 있어서,
 * 여기서 갈라 두면 맵마다 화면이 다른 게임이 된다. 반지름을 흔들 일이 생기면
 * 그 넷을 먼저 맵 단위로 옮겨야 한다(STATUS에 남긴다).
 */
/**
 * 표준 적 배치. 자동 조준이 "가장 가까운" 것을 고르는지 눈으로 보이게 흩어 둔다.
 * 적은 쓰러지면 이 자리로 돌아와 다시 선다 — 플레이어에게서 먼 자리라 숨 돌릴 틈이 생긴다.
 *
 * **다섯 중 하나는 돌진형, 하나는 방패병, 하나는 폭탄병이다**(DESIGN 9번). 활잡이만 있으면
 * 거리를 벌리는 것 하나로 모든 위협이 풀린다 — 섞어야 "물러날 곳"과 "버틸 곳"이 동시에 사라진다.
 * 넷이 함께 있으면 요구하는 것도 넷이 된다:
 * 계속 움직여라 · 옆으로 비켜라 · 돌아서 쏴라 · 물러나라.
 *
 * **폭탄병은 한복판 앞(0,-13)의 활잡이를 바꿔 세웠다**(세션 51). 다섯 자리 중 **가장 가까운
 * 자리**라 자동 조준이 이 적을 먼저 잡는다 — "물러나거나 쏘거나"의 쏘는 쪽이 처음부터 손에
 * 쥐여 있어야, 걸어오는 것이 무엇인지 배우기 전에 터지지 않는다(첫 폭발 중앙 5.1초).
 * 먼 자리(18,-9)에도 세워 보고 버렸다 — 판이 더 짧아지고(선 안 118 vs 122/180)
 * 손 놓고 서 있기가 26초로 내려가, 자리 하나가 게임의 성질을 바꿨다.
 *
 * **방패병은 활잡이 하나를 바꿔 세웠다. 수를 늘리지 않았다** — 적을 하나 더 세우면
 * 한 판 길이가 가장 먼저 움직인다(세션 13이 돌진형 하나로 한 판을 32초 늘렸다).
 * 돌진형(오른쪽)과 마주 보는 자리에 두어, 왼쪽으로 물러나도 오른쪽으로 물러나도
 * 각각 다른 것을 요구받게 했다.
 *
 * **하나인 이유는 재서 정했다.** 둘로 두면 한 판이 105초로 짧아져 3~5분 선(150~330초,
 * `tests/progression.test.ts`) 밑으로 떨어졌다. 돌진형은 화살과 달리 예고를 보고도
 * 발이 묶여 있으면 반드시 맞기 때문에, 한 마리가 활잡이 넷보다 무겁다.
 * 실측: 하나면 한 판 213초 · 서 있기 33초(활잡이만 있을 때의 42초보다 짧다 —
 * 한자리에 서 있는 사람에게 가장 아픈 적이다). 이 수를 늘리려면 그 두 검사부터 다시 볼 것.
 *
 * 자리는 좌우 중간 거리에 둔다 — 시작하자마자 코앞에서 튀어나오면 무슨 일인지 못 본다.
 */
const OPEN_LAYOUT: readonly EnemySpawn[] = [
  { x: 0, y: -13, kind: 'bomber' },
  { x: 12, y: 6, kind: 'charger' },
  { x: -12, y: 6, kind: 'shield' },
  { x: 18, y: -9 },
  { x: -18, y: -9 },
];

/**
 * **기둥 뜰** — 두 번째 아레나(DESIGN 10번).
 *
 * 빈 뜰과 다른 것은 **여섯 개의 기둥 하나뿐이다.** 적도 증원도 아레나 크기도 같다 —
 * 그래야 두 맵의 수치가 갈릴 때 무엇이 갈랐는지 알 수 있다(한 번에 하나만 흔든다).
 *
 * **자리를 정한 것은 하나의 규칙이다: 서서 시작하는 자리를 가리지 않는다.**
 * DESIGN 5번의 성질("가만히 서 있으면 쓰러진다")은 게임의 성질이지 맵의 성질이 아니다.
 * 맵 하나가 그것을 무르게 만들면 그 맵에서는 게임이 다른 게임이 된다.
 *
 * 처음에 **10.5m 고리**에 세워 보고 그것을 실제로 밟았다(씨앗 20판 실측):
 * **서 있기 40초 → 115초**. 활잡이가 서 있는 사람에게서 8~12m를 지키므로
 * (`ENEMY.keepDistance`·`approachDistance`) 그 띠에 기둥을 두면 적이 기둥 뒤에 서서 쏘게 되고,
 * 날아온 화살 중 몸에 닿는 몫이 **0.59 → 0.19**로 떨어진다. 한복판이 요새가 된 것이다.
 *
 * 그래서 **싸우는 띠 바깥(17m)** 으로 물렸다. 한복판에 선 사람과 그를 둘러싼 적은 둘 다
 * 고리 **안쪽**에 있어 기둥이 사이에 끼지 않는다 — 서 있기가 **42초**로 빈 뜰(39초)과 같다.
 * 대신 사람이 움직여 벽 쪽으로 나가는 순간부터 기둥이 사이에 든다. 판 내내 걷는 사람이
 * 아레나의 바깥 절반을 쓰므로(세션 27·28의 화면) 기둥은 거기서 제 몫을 한다.
 *
 * **재서 고른 두께 3.2m**(같은 자리에서 2.2 · 2.8 · 3.2을 재고, 10 · 15m 고리도 함께 봤다).
 * 얇으면 기둥이 있으나 마나이고(2.2m: 처치 171), 두꺼우면 벽과의 통로가 좁아진다.
 * 3.2m에서 180판 걷기/돌기 실측 — 중앙 **205/217초** · p90 **300/310** · 가장 긴 판 394/401 ·
 * 선 안 134/142판 · 처치 **157/181**(빈 뜰 186/206 — 기둥이 화살을 먹은 몫이다).
 * 빈 뜰의 같은 표는 중앙 214/227 · p90 305/315 · 선 안 137/151이다.
 * **판 길이는 거의 그대로이고 처치만 줄었다 — 기둥은 판을 순하게도 모질게도 만들지 않고
 * 어디서 싸울지만 바꾼다.** 그것이 이 맵이 노린 것이다.
 *
 * 남은 값들은 전부 겹치지 않게 잡은 것이고 `tests/maps.test.ts`가 지킨다:
 * 처음 선 적의 **몸이 기둥에 닿지 않는다**(15도 위상 · 겹쳐 세우면 판이 열리는 순간 적이
 * 밀려나 데이터에 적힌 자리와 화면이 어긋난다). 가장 빠듯한 것이 돌진형으로, 중심끼리
 * 4.70m · **몸과 기둥 사이 0.80m**다(미는 선은 기둥 3.2 + 몸 0.7 = 3.9m) ·
 * 바깥 끝 20.2m로 증원이 걸어 들어오는 고리(22m)와 어긋남 ·
 * 벽까지 5.8m · 기둥 사이 10.6m(달려오는 돌진형도 물러나는 활잡이도 지나간다) ·
 * 한복판은 비어 있다(시작하자마자 시야가 막히면 처음 하는 사람이 무슨 게임인지 못 본다).
 */
const PILLAR_RING = { count: 6, radius: 17, thickness: 3.2, offset: Math.PI / 12 } as const;

const PILLARS: readonly Obstacle[] = Array.from({ length: PILLAR_RING.count }, (_, i) => {
  const angle = PILLAR_RING.offset + (i * Math.PI * 2) / PILLAR_RING.count;
  return {
    x: Number((Math.cos(angle) * PILLAR_RING.radius).toFixed(3)),
    y: Number((Math.sin(angle) * PILLAR_RING.radius).toFixed(3)),
    radius: PILLAR_RING.thickness,
  };
});

/**
 * **그늘 뜰** — 세 번째 아레나(DESIGN 10번).
 *
 * **기둥 뜰의 여섯 중 셋을 들어낸 것이다.** 고리도 굵기도 위상도 그대로 두고
 * 반대쪽 셋만 뺐다(15 · 75 · 135도). 기둥 하나하나가 무엇을 하는지는 위에서 이미
 * 재 놨으므로, 여기서 새로 묻는 것은 **"가림이 한쪽에만 있으면 무엇이 달라지는가"**
 * 하나뿐이다. 굵기까지 함께 바꾸면 갈린 수치가 어느 쪽 때문인지 알 수 없다.
 *
 * **앞의 두 맵은 둘 다 어느 방향으로 돌아도 같은 맵이다.** 빈 뜰은 아무 데도 가림이 없고,
 * 기둥 뜰은 여섯이 고르게 둘러서서 **어디로 물러나도 가림이 같다**(아래 `cover` 표:
 * 벽 앞 어느 쪽이든 50~68도). 그래서 "어디로 갈까"라는 물음이 생기지 않는다.
 *
 * **이 맵이 가르는 것은 그 하나다: 물러날 곳이 둘로 갈린다.**
 *   - **그늘 쪽(15~135도)은 기둥 뜰과 똑같다** — 가림 50~68도.
 *   - **트인 쪽(195~345도)은 빈 뜰과 똑같다** — 가림 0도.
 * 기둥은 주인을 가리지 않으므로(`systems/obstacles.ts`) 그늘로 물러나면 적의 화살이
 * 끊기는 대신 내 화살도 끊긴다. 기둥 뜰이 "어디서 싸울지"를 바꿨다면,
 * 이 맵은 그것을 **고르게** 만든다. 이 성질은 `tests/maps.test.ts`가 지킨다.
 *
 * **셋을 어느 쪽에 두는지는 적 배치가 정했다.** 처음 서는 다섯 중 셋(0,-13 · 18,-9 ·
 * -18,-9)이 아래쪽에 있으므로 위쪽 셋을 남겼다 — 그늘은 적이 적은 쪽에 생긴다.
 * 아래로 물러나면 적이 많고 가림이 없고, 위로 물러나면 가림이 있고 내 화살도 끊긴다.
 * 위상 15도도 기둥 뜰에서 그대로 가져왔다. 옮기면 돌진형(12,6)의 몸이 기둥에 닿는다
 * (30도로 돌리면 몸과 기둥 사이가 3.70m로, 미는 선 3.8m 안이라 첫 프레임에 밀려난다).
 *
 * **재서 확인한 것**(씨앗 20판 중앙값 · 빈 뜰 / 기둥 뜰 / 그늘 뜰):
 * 한복판에 서 있기 **40 / 44 / 40초** · 한 판 **231 / 239 / 240초** ·
 * 처치 **206 / 191 / 202**. 가림이 반쪽에만 있으니 화살을 먹는 몫도 기둥 뜰의 반쯤이다.
 * 게임의 성질(서 있으면 쓰러진다 · 한 판 3~5분)은 어느 쪽으로도 움직이지 않았다.
 *
 * **처음 세운 안은 버렸다** — 셋을 45도 간격으로 더 좁게(90도 안에) 세우고 굵기를
 * 3.9m로 키운 안이다. 셋의 그늘이 서로 겹쳐 **한 자리에서 206도가 가려지는
 * 오목한 굴**이 생겼고(기둥 뜰의 가장 깊은 그늘은 150도다), 거기 숨어 서면
 * 손을 놓고도 **168초**를 버텼다(빈 뜰 39초 · 기둥 뜰 134초). DESIGN 5번이 말하는
 * "가만히 서 있으면 쓰러진다"가 그 자리에서만 다른 게임이 된 셈이다.
 * `tests/maps.test.ts`의 '반 넘게 가려지는 자리가 없다'가 그 안을 잡는다.
 */
const SHADE_ARC = { count: 3, radius: 17, thickness: 3.2, from: Math.PI / 12, step: Math.PI / 3 } as const;

const SHADE_PILLARS: readonly Obstacle[] = Array.from({ length: SHADE_ARC.count }, (_, i) => {
  const angle = SHADE_ARC.from + i * SHADE_ARC.step;
  return {
    x: Number((Math.cos(angle) * SHADE_ARC.radius).toFixed(3)),
    y: Number((Math.sin(angle) * SHADE_ARC.radius).toFixed(3)),
    radius: SHADE_ARC.thickness,
  };
});

/** 아레나 하나의 정의. 고르는 화면(`ui/MapSelect.ts`)이 이름과 한 줄 설명을 그대로 쓴다. */
export interface ArenaMap {
  /** 저장·URL에 쓰는 이름표. 한 번 정하면 바꾸지 않는다(고른 맵을 기억해 둔다). */
  id: string;
  /** 고르는 화면에 크게 적히는 이름. */
  name: string;
  /** 그 아래 한 줄. **무엇이 다른지**를 적는다 — 분위기를 적으면 고를 이유가 안 된다. */
  blurb: string;
  /** 이 맵에 선 기둥들. 빈 배열이면 규칙이 하나도 걸리지 않는다. */
  obstacles: readonly Obstacle[];
  /** 적이 처음 서는 자리. */
  enemies: readonly EnemySpawn[];
}

/**
 * 고를 수 있는 맵 전부. **첫 번째가 기본값이다**(아무것도 고르지 않았을 때 도는 맵).
 *
 * 순서를 바꾸지 마라 — 지금까지 잰 밸런스 수치는 전부 `open`의 것이고,
 * 기본값이 바뀌면 `npm test`·`npm run perf`의 표가 통째로 다른 맵의 표가 된다.
 */
export const MAPS: readonly ArenaMap[] = [
  {
    id: 'open',
    name: '빈 뜰',
    blurb: '가릴 것이 없다. 발로만 피한다.',
    obstacles: [],
    enemies: OPEN_LAYOUT,
  },
  {
    id: 'pillars',
    name: '기둥 뜰',
    blurb: '벽 앞에 여섯 기둥. 화살을 막아 주기도, 막아 버리기도 한다.',
    obstacles: PILLARS,
    enemies: OPEN_LAYOUT,
  },
  {
    id: 'shade',
    name: '그늘 뜰',
    blurb: '기둥 셋이 한쪽에만 섰다. 어느 쪽으로 물러날지 고르게 된다.',
    obstacles: SHADE_PILLARS,
    enemies: OPEN_LAYOUT,
  },
];

/** 기본 맵. 맵을 고르지 않고 만든 World가 도는 곳이다. */
export const DEFAULT_MAP: ArenaMap = MAPS[0] as ArenaMap;

/** 이름표로 맵을 찾는다. 모르는 이름표(옛 저장값·손으로 고친 주소)면 기본 맵. */
export function findMap(id: string | null | undefined): ArenaMap {
  return MAPS.find((m) => m.id === id) ?? DEFAULT_MAP;
}
