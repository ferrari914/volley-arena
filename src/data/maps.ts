/** 기본 맵. 맵을 고르지 않고 만든 World가 도는 곳이다. */
export const DEFAULT_MAP: ArenaMap = MAPS[0] as ArenaMap;

/** 이름표로 맵을 찾는다. 모르는 이름표(옛 저장값·손으로 고친 주소)면 기본 맵. */
export function findMap(id: string | null | undefined): ArenaMap {
  return MAPS.find((m) => m.id === id) ?? DEFAULT_MAP;
}
