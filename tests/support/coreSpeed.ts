/**
 * **이 바퀴가 얻은 코어가 빠른 코어였는지를 잰다.** 게임은 재지 않는다.
 *
 * 왜 있는가 — 세션 117(바퀴 #517)이 `npm test`를 **50.1초**에 통과시켰다. 기록에 적힌
 * 평소는 **29.8초**(세션 116 · 같은 469개)이고 그 사이 `src/`는 한 줄도 안 바뀌었다.
 * **이 저장소가 가진 자 셋이 모두 "성하다"고 답했다:**
 *   - `[기계]`(`sleepWatch.ts`)가 안 떴다 — 박동이 까먹은 것은 55초 동안 **54ms**다(잠은 0).
 *   - `[빠짐]`(`ranAll.ts`)이 안 떴다 — 18파일 469개가 다 돌았고 다 초록이다.
 *   - `CPU 몫`(`machine.ts`)이 **1.00**이다 — `/usr/bin/time`으로 재니
 *     `real 41.22 · user 40.74 · sys 0.68`이다. **한 순간도 밀려난 적이 없다.**
 *
 * 그런데 느렸다. 까닭은 **밀려난 것이 아니라 느린 코어에 앉은 것**이다.
 * 이 기계는 `Mac16,1`(Apple M4)이고 코어 10개가 **성능 4 + 효율 6**으로 갈린다.
 * 사람이 앞에서 딴 일을 하면(그날은 게임이 CPU 173% · Word 49%) 그쪽이 성능 코어를 쥐고,
 * 배경으로 도는 이 루프의 일꾼은 효율 코어로 밀려난다. **효율 코어는 밀려난 것이 아니라
 * 온전한 코어 하나다 — 그래서 CPU 몫은 1.00인데 같은 일이 세 배 더 든다.**
 *
 * **손으로 재서 확인했다**(아래 두 기준값이 그 값이다): 같은 계산이
 * 그냥 돌리면 **0.62 ns/회**, `taskpolicy -b`로 배경 QoS에 묶으면 **1.93 ns/회**다.
 *
 * **이것이 이 저장소의 네 번째 얼굴이고, 앞의 셋과 같은 병이다** — 세션 110(`grep`이
 * 인용문을 셌다) · 114(vitest가 안 돈 파일을 안 셌다) · 116(끝난 일이 계속 세어졌다)과
 * 뿌리가 같다: **다른 것을 같은 수로 세는 것.** 여기서 같은 수로 세어진 둘은
 * **"CPU 1초"**다. `machine.ts`의 머리말은 "빠르든 느리든 제 CPU를 온전히 쓰고 있으면
 * 몫이 1 근처다"라고 적었고 그 말은 맞다 — 다만 **그 1초가 하는 일의 양이 코어에 따라
 * 세 배 다르다.** 그러니 CPU 시간은 계산량의 자가 아니다.
 *
 * **이름표는 말하는 갈래마다 반드시 붙는다**(세션 119 · 바퀴 #521이 붙였다). 세션 117은
 * 다음 세션에게 "초를 적기 전에 `[코어]` 줄이 있는지부터 보라"고 남겼는데, 그 이름표가
 * **`stale` 갈래에만 있었다** — 곧 정작 봐야 할 `slow`·`mixed` 갈래는 이름 없이 떴다.
 * 세션 119가 실제로 걸렸다: 세 이름표를 `grep`해 하나도 안 나오자 50.1초를 "세 줄 다 없음"으로
 * 적을 뻔했고, 그때 출력에는 **1.9배짜리 느린 코어 경고가 그대로 찍혀 있었다.**
 * **이것이 이 저장소의 다섯 번째 얼굴이다** — 앞의 넷은 다른 것을 같은 수로 셌고(110·114·116·117),
 * 이번 것은 **말은 했는데 다음 세션이 찾으라고 배운 이름으로 말하지 않은 것**이다.
 * 아래 `coreAdviceFor`가 무엇을 말하든 첫 줄에 `[코어]`가 있는지를 검사가 매번 다시 잰다
 * (`tests/machine.test.ts` · ns를 훑어서 재므로 갈래를 새로 더해도 이름표를 빠뜨릴 수 없다).
 *
 * **무엇을 하라는 자인가** — 빨갛게 하지 않는다. 빨간 신호는 시간 초과가 이미 낸다.
 * 없던 것은 이름표다: 다음 세션이 "50초"를 보고 **게임을 파거나(세션 112가 35분을 버린 길)
 * 그 초를 새 평소로 베껴 적는 것(세션 114가 금지한 길)**을 막는 것이 이 파일이 하는 일의 전부다.
 */

/**
 * **손으로 잰 기준값 둘.** 검사 내용이 아니라 **이 기계의 성질**이라서, 검사가 늘어도
 * 썩지 않는다(벽시계 초를 기준선으로 두면 검사 하나 늘 때마다 거짓으로 울린다).
 * 기계가 바뀌면 `stale`로 스스로 알린다 — 아래 `coreVerdictOf`를 보라.
 *
 * 잰 법(그대로 다시 할 수 있다 · 2026-09-24 · 세션 117):
 *   `node -e '<아래 spin과 같은 계산 3억 번>'`  → 187 · 186 · 182ms → **0.62 ns/회**
 *   `taskpolicy -b node -e '<같은 것>'`        → 578 · 642 · 548ms → **1.93 ns/회**
 */
export const FAST_NS = 0.62;
export const SLOW_NS = 1.93;

/** 기준값보다 이만큼 빠르면 기준값이 썩은 것으로 본다(기계가 바뀌었다). */
export const STALE_AT = FAST_NS * 0.8;
/** 이 아래면 빠른 코어를 얻은 것으로 본다. 기준값의 1.5배까지는 클럭 흔들림으로 둔다. */
export const FAST_AT = FAST_NS * 1.5;
/** 이 위면 느린 코어에 앉은 것으로 본다(효율 코어 기준값의 3/4). */
export const SLOW_AT = SLOW_NS * 0.75;

export type CoreVerdict = 'stale' | 'fast' | 'mixed' | 'slow';

/** 계산 한 번에 몇 나노초가 들었는가. 기계 속도를 계산량과 무관한 단위로 적는다. */
export const nsPerIter = (ms: number, rounds: number): number =>
  rounds <= 0 ? 0 : (ms * 1e6) / rounds;

/** 빠른 코어에 견주어 몇 배 느린가. 벽시계가 그만큼 늘어난다는 뜻이다. */
export const slowdownVs = (ns: number): number => ns / FAST_NS;

/**
 * 속도 하나를 보고 무엇이라 부를지 정한다. **재는 일과 판단하는 일을 나눠 둬야
 * 판단을 손으로 박은 값으로 검사할 수 있다**(이 저장소가 세션 99부터 지키는 꼴이다).
 */
export const coreVerdictOf = (ns: number): CoreVerdict => {
  if (ns < STALE_AT) return 'stale';
  if (ns <= FAST_AT) return 'fast';
  if (ns >= SLOW_AT) return 'slow';
  return 'mixed';
};

/** 사람이 읽을 한 줄. 속도와 '벽시계가 몇 배로 늘어나는가'를 함께 적는다. */
export const describeCore = (ns: number): string =>
  `${ns.toFixed(2)} ns/회 (빠른 코어의 ${slowdownVs(ns).toFixed(1)}배 · 이 일꾼의 일이 그만큼 오래 걸린다)`;

/**
 * **이 바퀴에 뭐라고 적어 줄지를 정한다.** 판정 하나로 갈린다.
 * `fast`면 아무 말도 하지 않는다 — 할 말이 없을 때 조용한 것이 세션 116이 고친 그 병의 약이다.
 */
export const coreAdviceFor = (ns: number): string[] => {
  const verdict = coreVerdictOf(ns);
  if (verdict === 'fast') return [];

  if (verdict === 'stale') {
    return [
      `  [코어] 이 기계가 기준값보다 빠르다 (${describeCore(ns)}).`,
      `  **기준값이 썩었다** — 기계가 바뀐 것 같다. \`tests/support/coreSpeed.ts\`의`,
      '  `FAST_NS`·`SLOW_NS`를 머리말에 적힌 법으로 다시 재서 적어라. 게임과는 무관하다.',
    ];
  }

  const shared = [
    `  [코어] 이 바퀴는 ${verdict === 'slow' ? '느린 코어에서' : '느린 코어를 섞어'} 돌았다 — ${describeCore(ns)}`,
    '  **게임을 파지 마라. 이 초는 게임에 대해 아무것도 말하지 않는다.**',
    '  이 기계(Apple M4)는 코어가 성능 4 + 효율 6으로 갈린다. 사람이 앞에서 딴 일을 하면',
    '  배경으로 도는 이 일꾼이 효율 코어로 밀려나고, 같은 검사가 그만큼 오래 걸린다.',
    '  **밀려난 것이 아니라 느린 코어에 앉은 것이므로 `CPU 몫`은 1.00이고 `[기계]` 줄도 안 뜬다** —',
    '  이 저장소의 앞선 자 셋은 이 고장에 대해 모두 "성하다"고 답한다. 그래서 이 줄이 있다.',
    '  보는 법: `ps -Ao pcpu,command -r | head -5`(누가 성능 코어를 쥐고 있나) ·',
    '  `sysctl -n hw.perflevel0.logicalcpu hw.perflevel1.logicalcpu`(성능·효율 코어 수).',
    '',
    '  **이 배수를 검사 전체의 초에 그대로 곱하지 마라.** 여기 잰 것은 이 파일을 맡은 일꾼 하나이고,',
    '  검사 전체의 벽시계를 정하는 것은 가장 오래 가는 파일의 일꾼이다(그 둘은 다른 코어에 앉을 수 있다).',
    '  세션 117이 실제로 본 두 판이 그렇다: 2.6배인 바퀴가 37.4초 · 1.0배인 바퀴가 29.8초다.',
    '  **이 줄이 말하는 것은 방향이다 — "이 바퀴의 초는 앞 기록과 나란히 놓을 수 없다".**',
  ];

  if (verdict === 'slow') {
    return [
      ...shared,
      '',
      '  **그리고 이 바퀴의 초를 STATUS에 "평소"로 적지 마라.** 앞 기록의 초와 견주면',
      '  검사가 느려진 것으로 읽히지만, 느려진 것은 검사가 아니라 이 바퀴가 얻은 코어다.',
      '  적으려면 초와 함께 이 줄의 배수를 적어라 (세션 114의 규칙과 같은 자리다).',
    ];
  }
  return shared;
};

/**
 * 정해진 양의 계산. `tests/support/machine.ts`의 `spin`과 **같은 계산이어야 한다** —
 * 그래야 두 자가 같은 단위로 말한다(저쪽은 이 계산으로 CPU 몫을 재고, 이쪽은 속도를 잰다).
 * 값은 버리지만 최적화로 통째로 사라지지 않게 돌려준다.
 */
const spin = (rounds: number): number => {
  let acc = 0;
  for (let i = 0; i < rounds; i += 1) acc += Math.sqrt(i % 1024);
  return acc;
};

/**
 * 한 번 재는 양. 1억 번이면 빠른 코어에서 약 62ms, 느린 코어에서 약 193ms다 —
 * 두 값이 세 배 벌어지므로 이 길이로 충분히 갈린다(더 길게 잡으면 검사가 느려질 뿐이다).
 */
export const ROUNDS = 100_000_000;

/**
 * **이 일꾼이 지금 얻고 있는 코어의 속도.** 세 번 재서 가운뎃값을 쓴다 —
 * 한순간의 흔들림에 휘둘리지 않고, 그러면서 '이 바퀴가 실제로 얻은 속도'를 적는다
 * (가장 좋은 값을 쓰면 잠깐 스친 빠른 코어가 느린 바퀴를 성한 것으로 만든다).
 *
 * 처음 한 번은 버린다 — JIT가 덜 데워진 채로 재면 느린 코어처럼 보인다.
 */
export const measureCoreRate = (): number => {
  spin(ROUNDS / 10);

  const samples: number[] = [];
  for (let i = 0; i < 3; i += 1) {
    const before = performance.now();
    spin(ROUNDS);
    samples.push(nsPerIter(performance.now() - before, ROUNDS));
  }
  const sorted = samples.sort((a, b) => a - b);
  return sorted[1] ?? sorted[0] ?? 0;
};

/**
 * **같은 판정을 꼬리에 한 줄로 다시 적는다** (세션 120 · 바퀴 #522).
 *
 * 왜 따로 있는가 — 위 `coreAdviceFor`가 내는 묶음은 **이 파일을 맡은 일꾼 안에서** 찍히므로
 * 출력의 **앞머리**에 남는다(`tests/machine.test.ts`는 일찍 끝난다). 그런데 그 줄이 뜻을
 * 붙여 주는 수(`Duration`)는 출력의 **맨 끝**에 있다. 이 저장소의 다른 두 이름표는 그렇지
 * 않다 — `[기계]`는 `globalSetup`의 `teardown`에서, `[빠짐]`은 리포터의 `onTestRunEnd`에서
 * 찍혀 **둘 다 `Duration` 줄 아래**에 떨어진다(세션 120이 실제로 재서 확인했다).
 *
 * 곧 세 이름표는 **`grep`으로 읽을 때만 한 묶음이고, `tail`로 읽으면 둘만 보인다.**
 * 세션 120이 바로 그 자리에서 걸렸다: `npm test | tail -60`으로 읽고 초록을 확인한 뒤
 * **"493개 · 50.4초"를 앞 기록과 나란히 적었다.** 그때 출력 14번째 줄에 2.2배짜리 경고가
 * 그대로 있었다. 세션 119가 이름표를 제자리에 달아 `grep`이 찾게 만든 바로 다음 바퀴다.
 *
 * **이것이 이 저장소의 여섯 번째 얼굴이다.** 앞의 넷(110·114·116·117)은 다른 것을 같은
 * 수로 셌고, 다섯째(119)는 찾으라고 배운 이름으로 말하지 않았다. 이번 것은
 * **이름도 맞고 말도 했는데, 읽는 자리가 아닌 데서 말한 것**이다.
 *
 * 그래서 앞머리의 묶음은 그대로 둔다(잰 자리 옆에 근거가 있어야 한다). 꼬리에는 **수에
 * 뜻을 붙이는 데 필요한 것만** 적는다 — 이름표 · 배수 · "이 초를 앞 기록과 견주지 마라".
 * 말할지 말지는 `coreAdviceFor`가 정한 그대로 따른다. 둘이 따로 판단하면 언젠가 갈린다.
 */
export const coreTailFor = (ns: number): string[] => {
  if (coreAdviceFor(ns).length === 0) return [];

  if (coreVerdictOf(ns) === 'stale') {
    return [
      `  [코어] 이 기계가 기준값보다 빠르다 — ${describeCore(ns)}`,
      '  기준값이 썩었다(기계가 바뀐 것 같다). 게임과는 무관하다 · 자세한 것은 위쪽 `[코어]` 묶음에.',
    ];
  }

  return [
    `  [코어] 이 바퀴는 느린 코어를 얻었다 — ${describeCore(ns)}`,
    '  **바로 위 `Duration` 초를 앞 기록과 나란히 놓지 마라.** 느려진 것은 검사가 아니라 이 바퀴의 코어다.',
    '  STATUS에 적으려면 초와 함께 이 배수를 적어라 · 게임을 파지 마라 · 근거는 위쪽 `[코어]` 묶음에.',
  ];
};
